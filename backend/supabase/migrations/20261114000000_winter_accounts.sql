-- Winter accounts, installs, Pro status and the admin panel.
--
-- Who writes what:
--   * Edge function `app` (service role): installs, device links/tokens.
--   * Edge function `revenuecat-webhook` (service role): subscriptions, events.
--   * Admin panel (signed-in admin, through RLS): grants, admins.
-- The desktop app never talks to the database directly.

-- ---------------------------------------------------------------- admins

create table public.admins (
  email text primary key check (email = lower(email)),
  added_at timestamptz not null default now()
);

-- True when the signed-in user's (verified) email is in `admins`.
create function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.admins
    where email = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

-- --------------------------------------------------------------- installs

-- One row per Winter installation (random id generated by the app). Only
-- platform/version and timestamps are stored: no IP addresses, no names.
create table public.installs (
  install_id text primary key check (length(install_id) between 16 and 64),
  user_id uuid references auth.users (id) on delete set null,
  platform text not null default 'unknown',
  os_version text,
  app_version text,
  first_seen timestamptz not null default now(),
  last_seen timestamptz not null default now(),
  launches integer not null default 1
);
create index installs_user_idx on public.installs (user_id);
create index installs_last_seen_idx on public.installs (last_seen desc);

-- -------------------------------------------------- linking the desktop app

-- Device-code sign-in: the app shows a browser page with a random code; the
-- signed-in user approves it; the app exchanges the code for a device token.
create table public.device_links (
  code_hash text primary key,
  install_id text,
  user_id uuid references auth.users (id) on delete cascade,
  created_at timestamptz not null default now(),
  approved_at timestamptz,
  consumed_at timestamptz
);

-- Long-lived, revocable credentials of signed-in desktop apps.
create table public.devices (
  token_hash text primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  install_id text,
  platform text,
  created_at timestamptz not null default now(),
  last_seen timestamptz not null default now(),
  revoked_at timestamptz
);
create index devices_user_idx on public.devices (user_id);

-- ---------------------------------------------------------- Pro status

-- Latest `winter_pro` state per customer (RevenueCat app_user_id = Supabase
-- user id), kept up to date by the RevenueCat webhook and refreshed from the
-- RevenueCat API when stale.
create table public.subscriptions (
  app_user_id text primary key,
  status text not null check (status in
    ('trial', 'active', 'lifetime', 'expired', 'refunded', 'none')),
  product_id text,
  period_type text,           -- TRIAL / INTRO / NORMAL / PROMOTIONAL / PREPAID
  store text,
  environment text,           -- SANDBOX / PRODUCTION
  will_renew boolean,
  billing_issue boolean not null default false,
  purchased_at timestamptz,
  expires_at timestamptz,     -- null for lifetime
  had_trial boolean not null default false,
  converted_from_trial boolean not null default false,
  revenue_usd numeric(12, 2) not null default 0,
  management_url text,
  last_event text,
  updated_at timestamptz not null default now()
);

-- Raw webhook events (idempotency + audit trail).
create table public.revenuecat_events (
  id text primary key,
  type text not null,
  app_user_id text,
  payload jsonb not null,
  received_at timestamptz not null default now()
);
create index revenuecat_events_user_idx on public.revenuecat_events (app_user_id);

-- --------------------------------------------------------- free access

-- Free Pro access given by an admin, by email (works before the person has
-- signed up). `expires_at` null = forever.
create table public.grants (
  id bigint generated always as identity primary key,
  email text not null check (email = lower(email)),
  note text,
  expires_at timestamptz,
  created_by text not null default lower(coalesce(auth.jwt() ->> 'email', 'system')),
  created_at timestamptz not null default now(),
  revoked_at timestamptz
);
create index grants_email_idx on public.grants (email);

create function public.active_grant(p_email text)
returns public.grants language sql stable as $$
  select * from public.grants
  where email = lower(p_email) and revoked_at is null
    and (expires_at is null or expires_at > now())
  order by expires_at desc nulls first
  limit 1;
$$;

-- ------------------------------------------------------------------- RLS

alter table public.admins enable row level security;
alter table public.installs enable row level security;
alter table public.device_links enable row level security;
alter table public.devices enable row level security;
alter table public.subscriptions enable row level security;
alter table public.revenuecat_events enable row level security;
alter table public.grants enable row level security;

create policy "admins read admins" on public.admins
  for select to authenticated using (public.is_admin());
create policy "admins manage admins" on public.admins
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

create policy "admins read installs" on public.installs
  for select to authenticated using (public.is_admin());

create policy "admins read devices" on public.devices
  for select to authenticated using (public.is_admin());
create policy "admins revoke devices" on public.devices
  for update to authenticated using (public.is_admin()) with check (public.is_admin());
create policy "users read own devices" on public.devices
  for select to authenticated using (user_id = auth.uid());

create policy "admins read subscriptions" on public.subscriptions
  for select to authenticated using (public.is_admin());
create policy "users read own subscription" on public.subscriptions
  for select to authenticated using (app_user_id = auth.uid()::text);

create policy "admins read events" on public.revenuecat_events
  for select to authenticated using (public.is_admin());

create policy "admins manage grants" on public.grants
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- ------------------------------------------------------- admin read models

-- Everyone who signed in, with Pro status, free grant and install counts.
-- `security_invoker = false` (default) lets the view read auth.users; the
-- WHERE clause limits it to admins.
create view public.admin_users as
select
  u.id as user_id,
  u.email,
  u.created_at as signed_up_at,
  u.last_sign_in_at,
  s.status as subscription_status,
  s.product_id,
  s.period_type,
  s.store,
  s.environment,
  s.will_renew,
  s.billing_issue,
  s.purchased_at,
  s.expires_at,
  s.had_trial,
  s.converted_from_trial,
  coalesce(s.revenue_usd, 0) as revenue_usd,
  g.id as grant_id,
  g.expires_at as grant_expires_at,
  g.note as grant_note,
  (select count(*) from public.installs i where i.user_id = u.id) as installs,
  (select max(i.last_seen) from public.installs i where i.user_id = u.id) as last_seen,
  (select string_agg(distinct i.platform, ', ') from public.installs i where i.user_id = u.id) as platforms,
  case
    when g.id is not null then 'free'
    when s.status in ('trial', 'active', 'lifetime') then s.status
    when s.status in ('expired', 'refunded') then s.status
    else 'none'
  end as access
from auth.users u
left join public.subscriptions s on s.app_user_id = u.id::text
left join lateral (select * from public.active_grant(u.email)) g on g.id is not null
where public.is_admin();

grant select on public.admin_users to authenticated;

-- Headline numbers for the dashboard.
create function public.admin_stats() returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare result jsonb;
begin
  if not public.is_admin() then
    raise exception 'not an admin' using errcode = '42501';
  end if;
  select jsonb_build_object(
    'installs', (select count(*) from installs),
    'active_1d', (select count(*) from installs where last_seen > now() - interval '1 day'),
    'active_7d', (select count(*) from installs where last_seen > now() - interval '7 days'),
    'active_30d', (select count(*) from installs where last_seen > now() - interval '30 days'),
    'users', (select count(*) from auth.users),
    'trial', (select count(*) from subscriptions where status = 'trial'),
    'active', (select count(*) from subscriptions where status = 'active'),
    'lifetime', (select count(*) from subscriptions where status = 'lifetime'),
    'expired', (select count(*) from subscriptions where status in ('expired', 'refunded')),
    'free', (select count(distinct email) from grants
             where revoked_at is null and (expires_at is null or expires_at > now())),
    'trial_conversions', (select count(*) from subscriptions where converted_from_trial),
    'revenue_usd', (select coalesce(sum(revenue_usd), 0) from subscriptions),
    'platforms', (select coalesce(jsonb_object_agg(platform, n), '{}'::jsonb) from
                   (select platform, count(*) n from installs group by platform) p),
    'versions', (select coalesce(jsonb_object_agg(coalesce(app_version, '?'), n), '{}'::jsonb) from
                  (select app_version, count(*) n from installs group by app_version) v),
    'new_installs_14d', (select coalesce(jsonb_agg(jsonb_build_object('day', d, 'count', n) order by d), '[]'::jsonb) from
                  (select date_trunc('day', g)::date d,
                          (select count(*) from installs where date_trunc('day', first_seen) = date_trunc('day', g)) n
                   from generate_series(now() - interval '13 days', now(), interval '1 day') g) x)
  ) into result;
  return result;
end;
$$;

grant execute on function public.admin_stats() to authenticated;
revoke execute on function public.admin_stats() from anon;
